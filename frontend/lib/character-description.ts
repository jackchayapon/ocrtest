export function describeCharacters(text:string){
 const descriptions=Array.from(new Set(Array.from(text))).flatMap(char=>{
  if(names[char])return [`${char.trim()?char:"␣"} (${names[char]})`];
  if(/[\p{M}\p{P}\p{S}\p{C}\p{Z}]/u.test(char))return [`${char} (อักขระ Unicode U+${char.codePointAt(0)!.toString(16).toUpperCase().padStart(4,"0")})`];
  return [];
 });
 if(Array.from(text).length===1&&descriptions.length)return descriptions[0];
 return descriptions.length?`${text} — ${descriptions.join(", ")}`:text;
}
