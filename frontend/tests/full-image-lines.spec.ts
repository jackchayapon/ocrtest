import {test,expect} from '@playwright/test';
import {mockUX} from './ux-stability-fixture';

test('full image automatically splits GT and OCR, keeps blank and extra lines, and saves joined GT',async({page})=>{
 const state=await mockUX(page,1,{groundTruth:true});
 state.record.global_fields[0].roi={x1:0,y1:0,x2:600,y2:400};
 state.record.global_fields[0].ground_truth_raw='A\n\nB';
 state.record.ground_truth_raw='A\n\nB';
 state.record.runs.forEach(run=>{run.final_text='A\n\nB\nextra';});
 await page.goto('/workflow/ux-case/ground-truth?edit=1');
 await expect(page.getByRole('button',{name:'Whole Field',exact:true})).toHaveAttribute('aria-pressed','true');
 await expect(page.getByTestId('whole-gt-card')).toBeVisible();
 await expect(page.getByTestId('full-image-line-fields').locator('table')).toHaveCount(0);
 await page.getByRole('button',{name:'Sub-fields',exact:true}).click();
 await expect(page.getByTestId('field-gt-input')).toHaveCount(4);
 await expect(page.getByLabel('Ground Truth Field 02',{exact:true})).toHaveValue('');
 await expect(page.getByTestId('gt-field-preview')).toHaveCount(4);
 await page.getByRole('button',{name:'Field 03',exact:true}).click();
 await expect(page.getByLabel('Ground Truth Field 03',{exact:true})).toBeFocused();
 await page.getByLabel('Ground Truth Field 03',{exact:true}).fill('changed');
 await page.getByRole('button',{name:'Whole Field',exact:true}).click();
 await expect(page.getByLabel('Ground Truth ทั้งเอกสาร',{exact:true})).toHaveValue('A\n\nchanged');
 await page.getByLabel('Ground Truth ทั้งเอกสาร',{exact:true}).fill('A\n\nchanged\nnew');
 await page.getByRole('button',{name:'Sub-fields',exact:true}).click();
 await expect(page.getByLabel('Ground Truth Field 04',{exact:true})).toHaveValue('new');
 const pending=page.waitForRequest(r=>r.method()==='PUT'&&r.url().endsWith('/global-ground-truth'));
 await page.getByRole('button',{name:'บันทึก GT ฉบับร่าง',exact:true}).click();
 const payload=(await pending).postDataJSON();
 expect(payload.fields).toHaveLength(1);
 expect(payload.fields[0].ground_truth_raw).toBe('A\n\nchanged\nnew');
 expect(payload.ground_truth_raw).toBe('A\n\nchanged\nnew');
 await page.goto('/workflow/ux-case/ground-truth');
 await expect(page.getByRole('region',{name:'Evaluation Results',exact:true})).toBeVisible();
 await expect(page.getByTestId('full-image-line-fields')).toHaveCount(0);
 await expect(page.getByTestId('export-menu')).toBeVisible();
 await expect(page.getByTestId('comparison-text-row')).toHaveCount(1);
 await page.getByRole('button',{name:'Sub-fields',exact:true}).click();
 await expect(page.getByTestId('comparison-text-row')).toHaveCount(4);
 await expect(page.getByTestId('comparison-text-row').nth(3)).toContainText('extra');
 await page.getByRole('button',{name:'Whole Field',exact:true}).click();
 await expect(page.getByTestId('comparison-text-row')).toHaveCount(1);
 await page.getByRole('button',{name:'กลับไปแก้ Ground Truth',exact:true}).click();
 await page.getByRole('button',{name:'ยืนยันเพื่อคำนวณ',exact:true}).click();
 await expect(page.getByRole('region',{name:'Evaluation Results',exact:true})).toBeVisible();
 await expect(page.getByTestId('full-image-line-fields')).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Whole Field',exact:true})).toHaveAttribute('aria-pressed','true');
 expect(state.jobPosts).toBe(0);
});
