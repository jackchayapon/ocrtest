import {test,expect} from '@playwright/test';
import {randomUUID} from 'node:crypto';
import {readFileSync} from 'node:fs';
import {waitForJobResults} from './job-results';

const api=process.env.E2E_API_URL||'http://127.0.0.1:8100';

for(const count of [40,60,80])test(`${count} Fields x3: one real Job, bounded selection, bulk GT, focus and refresh`,async({page,request})=>{
 test.setTimeout(120000);
 const errors:string[]=[];let jobs=0,bulk=0,individual=0;
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(r.method()==='POST'&&r.url().endsWith('/jobs'))jobs++;if(r.method()==='PUT'&&r.url().endsWith('/global-ground-truth'))bulk++;if(r.method()==='PUT'&&/global-fields\/[^/]+\/ground-truth$/.test(r.url()))individual++;});
 const document=await(await request.post(api+'/api/documents',{multipart:{file:{name:'synthetic-multifield.png',mimeType:'image/png',buffer:readFileSync('public/sample-document.png')}}})).json();
 const c=await(await request.post(api+'/api/test-cases',{data:{document_id:document.id,workflow:'global'}})).json();
 const fields=Array.from({length:count},(_,i)=>({id:randomUUID(),field_index:i+1,source:'manual',ground_truth_raw:'',roi:{x1:Math.floor(i%8*document.width/8+2),y1:Math.floor(Math.floor(i/8)*document.height/10+2),x2:Math.floor((i%8+1)*document.width/8-2),y2:Math.floor((Math.floor(i/8)+1)*document.height/10-2)}}));
 const saved=await request.put(api+`/api/test-cases/${c.id}/global-fields`,{data:{fields,confirmed:true}});expect(saved.status()).toBe(200);
 await page.goto(`/workflow/${c.id}/layout`);await expect(page.getByTestId('global-field-nav')).toHaveCount(count);
 if(count===80)await expect(page.getByRole('button',{name:'เพิ่มกรอบ Manual',exact:true})).toBeDisabled();
 await page.goto(`/workflow/${c.id}/pipelines`);
 await expect(page.getByTestId('job-workload-limits')).toContainText('80 Fields และ 3 Pipelines');
 const options=page.getByTestId('pipeline-options');
 await expect(options.locator('input:checked')).toHaveCount(3);
 await expect(page.getByRole('button',{name:'Run OCR',exact:true})).toBeEnabled();
 const fourth=options.locator('input').nth(3);await expect(fourth).toBeDisabled();
 const first=options.locator('input').first();await first.uncheck();await expect(fourth).toBeEnabled();await first.check();
 const accepted=waitForJobResults(page);await page.getByRole('button',{name:'Run OCR',exact:true}).click();
 const result=await(await accepted).json();expect(result.runs).toHaveLength(3);
 expect(result.runs.every((r:{fields:unknown[]})=>r.fields.length===count)).toBe(true);
 await expect(page).toHaveURL(/ground-truth\?edit=1$/);
 await page.getByRole('button',{name:'Sub-fields',exact:true}).click();
 const last=page.getByLabel(`Ground Truth Field ${count}`,{exact:true});await last.scrollIntoViewIfNeeded();await last.focus();await expect(last).toBeFocused();
 const started=Date.now();await last.fill('กิ่ ทดสอบ 123');await expect(last).toHaveValue('กิ่ ทดสอบ 123');expect(Date.now()-started).toBeLessThan(2000);
 await page.getByRole('button',{name:'Whole Field',exact:true}).click();
 await page.getByLabel('Ground Truth ทั้งเอกสาร',{exact:true}).fill(Array.from({length:count},(_,i)=>`ทดสอบ Field ${i+1}`).join('\n'));
 const evaluated=page.waitForResponse(r=>r.url().endsWith('/evaluate')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'ยืนยันเพื่อคำนวณ',exact:true}).click();expect((await evaluated).status()).toBe(200);
 expect(bulk).toBe(1);expect(individual).toBe(0);expect(jobs).toBe(1);
 const record=await(await request.get(api+`/api/test-cases/${c.id}`)).json();
 expect(record.global_fields).toHaveLength(count);expect(record.global_fields.every((f:{confirmed_at:string})=>!!f.confirmed_at)).toBe(true);
 expect(record.runs.every((r:{fields:{evaluation:unknown}[]})=>r.fields.length===count&&r.fields.every(f=>!!f.evaluation))).toBe(true);
 const current=await(await request.get(api+`/api/test-cases/${c.id}/jobs`)).json();
 expect(current.status).toBe('completed');expect(current.completed_units).toBe(count*3);
 await page.setViewportSize({width:390,height:844});await page.goto(`/workflow/${c.id}/ground-truth?edit=1`);
 await page.getByRole('button',{name:'Sub-fields',exact:true}).click();await expect(page.getByLabel(`Ground Truth Field ${count}`,{exact:true})).toHaveValue(`ทดสอบ Field ${count}`);
 await page.reload();await page.getByRole('button',{name:'Sub-fields',exact:true}).click();await expect(page.getByLabel(`Ground Truth Field ${count}`,{exact:true})).toHaveValue(`ทดสอบ Field ${count}`);
 expect(jobs).toBe(1);expect(errors).toEqual([]);
 expect((await request.post(api+`/api/test-cases/${c.id}/jobs`,{data:{pipelines:['a','b','c','d'],idempotency_key:randomUUID()}})).status()).toBe(422);
 expect((await(await request.get(api+`/api/test-cases/${c.id}/jobs`)).json()).job_id).toBe(current.job_id);
});
