import {test, expect} from "@playwright/test";
import {readFileSync} from "node:fs";
import {randomUUID} from "node:crypto";

const api = process.env.E2E_API_URL || "http://127.0.0.1:8100";

test("public encrypted provider through UI, mixed durable Job, GT, metrics, History, export and deletion", async ({page, request}) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/settings/pipelines");
  await page.getByRole("button", {name: "เพิ่ม Pipeline", exact: true}).click();
  await page.getByLabel("Pipeline execution source").selectOption("external");
  const name = "Shared synthetic " + randomUUID();
  const form = page.getByRole("form", {name: "ตั้งค่า External Pipeline"});
  await form.getByLabel("ชื่อ Pipeline", {exact: true}).fill(name);
  await form.getByLabel("ชื่อ Provider", {exact: true}).fill(name);
  await form.getByLabel("API Endpoint URL").fill("https://shared-synthetic.invalid/ocr");
  await form.getByLabel("Readiness URL (ไม่บังคับ)").fill("https://shared-synthetic.invalid/ready");
  await form.getByLabel("Response Adapter").selectOption("text_json");
  await form.getByLabel("ใช้ API Key", {exact: true}).check();
  await form.getByLabel("API Key", {exact: true}).fill("synthetic-browser-key");
  await form.getByRole("button", {name: "บันทึก Pipeline", exact: true}).click();
  const card = page.locator("section").filter({has: page.getByRole("heading", {name, exact: true})});
  await card.getByRole("button", {name: "Test Connection", exact: true}).click();
  await expect(card.getByText("Provider reports ready and authentication accepted. Inference has not been tested.", {exact: true})).toBeVisible();
  const configs = await (await request.get(api + "/api/pipelines")).json();
  const external = configs.find((value: {name: string}) => value.name === name);
  const providers = await request.get(api + "/api/external-providers");
  expect(await providers.text()).not.toContain("synthetic-browser-key");
  const providerPath = api + "/api/external-providers/" + external.external_provider.provider_id;
  const updatedDefinition = {name, endpoint: "https://shared-synthetic.invalid/ocr-v2",
    readiness_url: "https://shared-synthetic.invalid/ready", auth_mode: "bearer", response_adapter: "text_json", credential_action: "keep"};
  const updated = await request.put(providerPath, {data: updatedDefinition});
  expect(updated.status()).toBe(200);
  expect((await updated.json()).api_key_configured).toBe(true);
  expect((await request.put(providerPath, {data: {...updatedDefinition, enabled: false}})).status()).toBe(200);
  expect((await (await request.get(api + "/api/pipelines/external-providers")).json()).some((value: {id: string}) => value.id === external.external_provider.provider_id)).toBe(false);
  expect((await request.put(providerPath, {data: {...updatedDefinition, enabled: true}})).status()).toBe(200);
  const internalResponse = await request.post(api + "/api/pipelines", {data: {name: "Shared integration internal mock", source: "custom", execution_mode: "integrated", version: "6"}});
  expect(internalResponse.status()).toBe(201);
  const internal = await internalResponse.json();
  const upload = await request.post(api + "/api/documents", {multipart: {file: {
    name: "shared-synthetic.png", mimeType: "image/png", buffer: readFileSync("tests/fixtures/openthai-thai-english.png")}}});
  expect(upload.status()).toBe(201);
  const document = await upload.json();
  const created = await request.post(api + "/api/test-cases", {data: {document_id: document.id, workflow: "global"}});
  expect(created.status()).toBe(201);
  const record = await created.json();
  const field = {id: randomUUID(), field_index: 1, source: "manual", roi: {x1: 0, y1: 0, x2: 780, y2: 250}, ground_truth_raw: "ไทย ABC"};
  expect((await request.put(api + `/api/test-cases/${record.id}/global-fields`, {data: {fields: [field], confirmed: true}})).status()).toBe(200);
  let submissions = 0;
  page.on("request", req => {if (req.method() === "POST" && req.url().endsWith("/jobs")) submissions++;});
  await page.goto(`/workflow/${record.id}/pipelines`);
  await expect(page.getByRole("checkbox", {name: `เลือก ${name}`, exact: true})).toBeVisible();
  for (const checkbox of await page.getByTestId("pipeline-options").getByRole("checkbox").all()) await checkbox.uncheck();
  await page.getByRole("checkbox", {name: `เลือก ${name}`, exact: true}).check();
  await page.getByRole("checkbox", {name: "เลือก Shared integration internal mock", exact: true}).check();
  const accepted = page.waitForResponse(response => response.request().method() === "POST" && response.url().endsWith("/jobs"));
  await page.getByRole("button", {name: "Run OCR", exact: true}).click();
  const response = await accepted;
  expect(response.status()).toBe(202);
  const job = await response.json();
  await page.reload();
  await expect(page).toHaveURL(/ground-truth\?edit=1$/, {timeout: 45000});
  const result = await (await request.get(api + `/api/ocr-jobs/${job.job_id}/results`)).json();
  expect(result.runs).toHaveLength(2);
  const run = result.runs.find((value: {pipeline_id: string}) => value.pipeline_id === external.pipeline_id);
  expect(run.status).toBe("success");
  expect(run.fields[0].ocr_text).toBe("ไทย ABC");
  expect(result.runs.find((value: {pipeline_id: string}) => value.pipeline_id === internal.pipeline_id).status).toBe("success");
  expect((await request.put(api + `/api/test-cases/${record.id}/global-fields/${field.id}/ground-truth`, {data: {ground_truth_raw: "ไทย ABC"}})).status()).toBe(200);
  const evaluation = await request.post(api + `/api/test-cases/${record.id}/evaluate`, {data: {mode: "per_field", global_field_ids: [field.id]}});
  expect(evaluation.status()).toBe(200);
  const evaluated = (await evaluation.json()).runs.find((value: {pipeline_id: string}) => value.pipeline_id === external.pipeline_id).fields[0].evaluation;
  expect(evaluated.cer).toBe(0); expect(evaluated.wer).toBe(0); expect(evaluated.exact_match).toBe(true);
  expect((await request.get(api + `/api/test-cases/${record.id}/evaluation-report`)).status()).toBe(200);
  await page.goto(`/workflow/${record.id}/evaluation`);
  await expect(page.getByTestId("comparison-scroll")).toBeVisible();
  await page.goto("/history");
  await expect(page.getByText("shared-synthetic.png", {exact: true}).first()).toBeVisible();
  expect(submissions).toBe(1); expect(errors).toEqual([]);
  expect((await request.delete(api + `/api/pipelines/${external.pipeline_id}`)).status()).toBe(204);
  expect((await request.delete(api + `/api/external-providers/${external.external_provider.provider_id}`)).status()).toBe(204);
  expect((await request.delete(api + `/api/pipelines/${internal.pipeline_id}`)).status()).toBe(204);
});
